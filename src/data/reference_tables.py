import csv
import math
from pathlib import Path
from collections import defaultdict
from src.domain.device import PowerCurvePoint, PowerTracePoint


_CURVES = (
    ("GPU-H100", "compute", 0.0, 0.35), ("GPU-H100", "compute", 0.5, 0.55), ("GPU-H100", "compute", 1.0, 0.70),
    ("Chiller-500kW", "cooling", 0.0, 35.0), ("Chiller-500kW", "cooling", 0.5, 120.0), ("Chiller-500kW", "cooling", 1.0, 220.0),
    ("UPS-1MW", "power_distribution", 0.0, 8.0), ("UPS-1MW", "power_distribution", 0.5, 18.0), ("UPS-1MW", "power_distribution", 1.0, 35.0),
    ("ToR-48p", "network", 0.0, 0.10), ("ToR-48p", "network", 0.5, 0.18), ("ToR-48p", "network", 1.0, 0.28),
)

# Grid-scale simulation calibration. The trace shape and utilization stay
# device-derived, while power is scaled to represent an equipment cluster.
_TRACE_POWER_SCALE = 100.0


def generate_reference_tables(output_dir: Path) -> dict[str, Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    curve_path = output_dir / "equipment_power_curves.csv"
    with curve_path.open("w", newline="", encoding="utf-8") as target:
        writer = csv.writer(target)
        writer.writerow(("model", "equipment_type", "utilization", "power_kw"))
        writer.writerows(_CURVES)
    trace_path = output_dir / "equipment_power_timeseries.csv"
    generate_equipment_power_timeseries(trace_path)
    return {"equipment_power_curves": curve_path, "equipment_power_timeseries": trace_path}


def generate_equipment_power_timeseries(path: Path, period_seconds: int = 240) -> Path:
    """Generate dense, one-second representative traces for each device type."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    gpu_util = []
    for t in range(period_seconds):
        cycle = t % 40
        active = 10 <= cycle <= 36
        base = 0.91 if active else 0.96
        ripple = (0.045 * math.sin(2 * math.pi * t / 3.7)
                  + 0.025 * math.sin(2 * math.pi * t / 1.35)) if active else 0.008 * math.sin(t / 2)
        dips = 0.0
        if active and 13 <= cycle <= 16:
            dips -= 0.22 * math.sin(math.pi * (cycle - 13) / 3)
        if active and 28 <= cycle <= 31:
            dips -= 0.18 * math.sin(math.pi * (cycle - 28) / 3)
        gpu_util.append(max(0.56, min(1.02, base + ripple + dips)))
    thermal = []
    state = 0.6
    for t, value in enumerate(gpu_util):
        demand = max(0.45, min(1.0, 0.25 + 0.78 * value - (0.12 * math.sin(math.pi * (t % 80) / 18) if t % 80 <= 18 else 0)))
        state += 0.035 * (demand - state)
        thermal.append(max(0.55, min(0.98, 0.52 + 0.43 * state)))
    ups = []
    state = 0.7
    network = []
    for t, value in enumerate(gpu_util):
        state += 0.16 * (0.58 + 0.34 * value + 0.015 * math.sin(t / 9) - state)
        ups.append(max(0.55, min(0.98, state)))
        network.append(max(0.48, min(0.90, 0.53 + 0.23 * value + 0.035 * math.sin(t / 2.8) + 0.025 * math.sin(t / 0.9))))
    records = []
    for t in range(period_seconds):
        records.extend([
            ("GPU-H100", "compute", t, gpu_util[t], 0.35 + 0.35 * gpu_util[t]),
            ("Chiller-500kW", "cooling", t, thermal[t], 35.0 + 185.0 * thermal[t]),
            ("UPS-1MW", "power_distribution", t, ups[t], 8.0 + 27.0 * (ups[t] ** 0.72)),
            ("ToR-48p", "network", t, network[t], 0.10 + 0.18 * network[t]),
        ])
    with path.open("w", newline="", encoding="utf-8") as target:
        writer = csv.writer(target)
        writer.writerow(("model", "equipment_type", "period_seconds", "time_s", "utilization", "power_kw"))
        writer.writerows((model, equipment_type, period_seconds, time_s, round(utilization, 6), round(round(power, 6) * _TRACE_POWER_SCALE, 6))
                         for model, equipment_type, time_s, utilization, power in records)
    return path


def load_equipment_power_curves(path: Path) -> dict[str, list[PowerCurvePoint]]:
    """Load reusable curve data generated by :func:`generate_reference_tables`."""
    curves: dict[str, list[PowerCurvePoint]] = defaultdict(list)
    with Path(path).open(newline="", encoding="utf-8") as source:
        for row in csv.DictReader(source):
            curves[row["model"]].append(
                PowerCurvePoint(
                    utilization=float(row["utilization"]),
                    power_kw=float(row["power_kw"]),
                )
            )
    return dict(curves)


def load_equipment_power_traces(path: Path) -> dict[str, tuple[int, list[PowerTracePoint]]]:
    traces: dict[str, list[PowerTracePoint]] = defaultdict(list)
    periods: dict[str, int] = {}
    with Path(path).open(newline="", encoding="utf-8") as source:
        for row in csv.DictReader(source):
            model = row["model"]
            periods[model] = int(row["period_seconds"])
            traces[model].append(PowerTracePoint(
                time_s=int(row["time_s"]),
                utilization=float(row["utilization"]),
                power_kw=float(row["power_kw"]),
            ))
    return {model: (periods[model], points) for model, points in traces.items()}
